//! Four-limb CIOS Montgomery arithmetic for BMI2/ADX x86-64.
//! Each row accumulates low products through CF and high products through
//! OF. With reduced inputs and p < 2^254, the five-limb accumulator cannot
//! overflow; after four rows one subtraction reduces the result.
//! sum2 accumulates both products before each Montgomery reduction.

#[inline(always)]
pub fn add(a: [u64; 4], b: [u64; 4], p: [u64; 4]) -> [u64; 4] {
    let [mut r0, mut r1, mut r2, mut r3] = a;
    // SAFETY: b and p point to four initialized limbs. The sum is below
    // 2p < 2^255, so there is no carry beyond the four output limbs.
    unsafe {
        core::arch::asm!(
            "add {r0}, qword ptr [{bp}]",
            "adc {r1}, qword ptr [{bp}+8]",
            "adc {r2}, qword ptr [{bp}+16]",
            "adc {r3}, qword ptr [{bp}+24]",
            "mov {d0}, {r0}", "mov {d1}, {r1}", "mov {d2}, {r2}", "mov {d3}, {r3}",
            "sub {d0}, qword ptr [{pp}]",
            "sbb {d1}, qword ptr [{pp}+8]",
            "sbb {d2}, qword ptr [{pp}+16]",
            "sbb {d3}, qword ptr [{pp}+24]",
            "cmovnc {r0}, {d0}", "cmovnc {r1}, {d1}", "cmovnc {r2}, {d2}", "cmovnc {r3}, {d3}",
            r0=inout(reg) r0, r1=inout(reg) r1, r2=inout(reg) r2, r3=inout(reg) r3,
            bp=in(reg) b.as_ptr(),pp=in(reg) p.as_ptr(),
            d0=out(reg) _,d1=out(reg) _,d2=out(reg) _,d3=out(reg) _,
            options(readonly,nostack),
        );
    }
    [r0, r1, r2, r3]
}

#[inline(always)]
pub fn sub(a: [u64; 4], b: [u64; 4], p: [u64; 4]) -> [u64; 4] {
    let [mut r0, mut r1, mut r2, mut r3] = a;
    // SAFETY: every memory operand reads an initialized modulus/operand
    // limb. A borrow adds p with a mask; all arithmetic is branch-free.
    unsafe {
        core::arch::asm!(
            "sub {r0}, qword ptr [{bp}]",
            "sbb {r1}, qword ptr [{bp}+8]",
            "sbb {r2}, qword ptr [{bp}+16]",
            "sbb {r3}, qword ptr [{bp}+24]",
            "sbb {mask}, {mask}",
            "mov {d0}, qword ptr [{pp}]",
            "mov {d1}, qword ptr [{pp}+8]",
            "mov {d2}, qword ptr [{pp}+16]",
            "mov {d3}, qword ptr [{pp}+24]",
            "and {d0}, {mask}", "and {d1}, {mask}", "and {d2}, {mask}", "and {d3}, {mask}",
            "add {r0}, {d0}", "adc {r1}, {d1}", "adc {r2}, {d2}", "adc {r3}, {d3}",
            r0=inout(reg) r0, r1=inout(reg) r1, r2=inout(reg) r2, r3=inout(reg) r3,
            bp=in(reg) b.as_ptr(),pp=in(reg) p.as_ptr(),
            d0=out(reg) _,d1=out(reg) _,d2=out(reg) _,d3=out(reg) _,mask=out(reg) _,
            options(readonly,nostack),
        );
    }
    [r0, r1, r2, r3]
}

#[inline(always)]
pub fn neg(a: [u64; 4], p: [u64; 4]) -> [u64; 4] {
    sub([0; 4], a, p)
}

#[inline(always)]
