# Emits a straight-line SOS Montgomery square for 8 x 32-bit limbs in MSL.
L = []
w = L.append
w("// A Montgomery square in straight-line SOS: 36 products for the square")
w("// (cross products once, doubled), 64 for the reduction; every index is")
w("// a constant, so the array stays in registers. Generated by")
w("// tools/gen_metal_sqr.py.")
w("template <typename F>")
w("inline F field_square(thread const F &x, constant uint *q, uint inv) {")
w("  const uint a0 = x.v[0], a1 = x.v[1], a2 = x.v[2], a3 = x.v[3], a4 = x.v[4], a5 = x.v[5], a6 = x.v[6], a7 = x.v[7];")
w("  uint " + ", ".join(f"t{k} = 0" for k in range(17)) + ";")
w("  ulong uv;")
w("  uint c;")
for i in range(8):
    w("  c = 0;")
    for j in range(i + 1, 8):
        w(f"  uv = (ulong)a{i} * a{j} + t{i+j} + c; t{i+j} = (uint)uv; c = (uint)(uv >> 32);")
    w(f"  t{i+8} = c;")
# double t1..t15 into t1..t16
w(f"  t16 = t15 >> 31;")
for k in range(15, 1, -1):
    w(f"  t{k} = (t{k} << 1) | (t{k-1} >> 31);")
w("  t1 = t1 << 1;")
# add squares
w("  c = 0;")
for i in range(8):
    w(f"  uv = (ulong)a{i} * a{i} + t{2*i} + c; t{2*i} = (uint)uv;")
    w(f"  uv = (uv >> 32) + t{2*i+1}; t{2*i+1} = (uint)uv; c = (uint)(uv >> 32);")
w("  t16 += c;")
# reduction
w("  uint m;")
for i in range(8):
    w(f"  m = t{i} * inv; c = 0;")
    for j in range(8):
        w(f"  uv = (ulong)m * q[{j}] + t{i+j} + c; t{i+j} = (uint)uv; c = (uint)(uv >> 32);")
    for k in range(i + 8, 17):
        w(f"  uv = (ulong)t{k} + c; t{k} = (uint)uv; c = (uint)(uv >> 32);")
w("  const uint r[8] = {" + ", ".join(f"t{k}" for k in range(8, 16)) + "};")
w("  return field_reduce_once<F>(r, q);")
w("}")
print("\n".join(L))
